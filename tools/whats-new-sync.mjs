#!/usr/bin/env node
/**
 * whats-new-sync.mjs — publish What's New entries automatically from the PR lifecycle.
 *
 * One committed data file is the source of truth (`backlog/whats-new-auto.json`); the generated
 * TypeScript module (`src/core/whatsnew.auto.ts`) is what the console, server and offline demo
 * actually read. This script never executes pull-request code: it only parses the GitHub event
 * payload (title, body, labels, dates) and calls the domain drafter in `src/core/whatsnew.ts`.
 *
 * Modes (all offline-safe except when they call the GitHub API):
 *   --check                     regenerate in memory and fail if either committed file drifted
 *   --event                     use $GITHUB_EVENT_PATH / $GITHUB_EVENT_NAME (PR or push)
 *   --backfill                  fetch PRs merged after the watermark and ship them (+ self-heal)
 *   --pr=42 [--stage=proposed]   fetch one PR (local backfill / replay)
 *   --comment                   also upsert a sticky PR comment with the drafted note
 *   --since=ISO                 override the backfill watermark (workflow_dispatch)
 *
 * Requires `npm run build:server` for mutation modes (`--check` never needs a build).
 */
import { appendFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = resolve(import.meta.dirname, '..');
const DATA = resolve(ROOT, 'backlog/whats-new-auto.json');
const GENERATED = resolve(ROOT, 'src/core/whatsnew.auto.ts');
const COMPILED = resolve(ROOT, 'dist-server/core/whatsnew.js');
const ARGV = process.argv.slice(2);
const has = (flag) => ARGV.includes(flag);
const value = (name, fallback) => ARGV.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3) ?? fallback;
const COMMENT_MARKER = '<!-- whats-new-bot -->';

function renderData(feed) {
  return `${JSON.stringify({ version: 1, lastMergedAt: feed.lastMergedAt, entries: feed.entries }, null, 2)}\n`;
}

function renderGenerated(feed) {
  return [
    '/**',
    ' * AUTO-GENERATED by tools/whats-new-sync.mjs from backlog/whats-new-auto.json — do not edit by hand.',
    ' *',
    ' * One entry per pull request: `proposed` on PR open, `shipped` on merge into main. The generator,',
    ' * the workflow and the guard test are the only writers. Rebuild the offline demo after regeneration.',
    ' */',
    "import type { WhatsNewEntry } from './whatsnew.js';",
    '',
    `export const AUTO_WHATS_NEW_ENTRIES: ReadonlyArray<WhatsNewEntry> = ${JSON.stringify(feed.entries, null, 2)};`,
    '',
    `export const WHATS_NEW_FEED_WATERMARK = ${JSON.stringify(feed.lastMergedAt)};`,
    '',
  ].join('\n');
}

function readFeed() {
  const raw = JSON.parse(readFileSync(DATA, 'utf8'));
  if (raw.version !== 1 || typeof raw.lastMergedAt !== 'string' || !Array.isArray(raw.entries)) {
    throw new Error(`${DATA}: expected { version: 1, lastMergedAt, entries[] }`);
  }
  return { version: 1, lastMergedAt: raw.lastMergedAt, entries: raw.entries };
}

function output(name, text) {
  const path = process.env.GITHUB_OUTPUT;
  if (path) appendFileSync(path, `${name}=${String(text).replace(/[\r\n]/g, ' ')}\n`);
}

async function domain() {
  if (!existsSync(COMPILED)) {
    throw new Error('dist-server/core/whatsnew.js is missing — run `npm run build:server` before whats-new-sync.mjs');
  }
  return import(pathToFileURL(COMPILED).href);
}

/** Validate, canonicalise and write both committed files. Idempotent: no write when nothing changed. */
async function writeFeed(feed, { check = false } = {}) {
  // --check runs in plain CI before anything is built, so it compares the committed files
  // without importing the compiled domain module.
  const d = check ? null : await domain();
  if (d) for (const entry of feed.entries) d.assertPublishableEntry(entry);
  const ids = new Set(feed.entries.map((e) => e.id));
  if (ids.size !== feed.entries.length) throw new Error('duplicate What\'s New entry ids in the generated feed');
  const canonical = { version: 1, lastMergedAt: feed.lastMergedAt, entries: d ? d.sortWhatsNewEntries(feed.entries) : feed.entries };
  const nextData = renderData(canonical);
  const nextGenerated = renderGenerated(canonical);
  const oldData = readFileSync(DATA, 'utf8');
  const oldGenerated = readFileSync(GENERATED, 'utf8');
  const changed = nextData !== oldData || nextGenerated !== oldGenerated;
  if (check) {
    if (changed) throw new Error('What\'s New feed drifted — run `npm run whats-new:sync` (or the workflow) and commit both files');
    console.log(`whats-new: ${canonical.entries.length} generated entr(y/ies) in sync`);
    return { changed: false, feed: canonical };
  }
  if (changed) {
    writeFileSync(DATA, nextData);
    writeFileSync(GENERATED, nextGenerated);
  }
  const pending = canonical.entries.filter((e) => e.stage === 'proposed').length;
  console.log(`whats-new: ${canonical.entries.length} generated entries (${pending} proposed), watermark ${canonical.lastMergedAt}, ${changed ? 'updated' : 'no change'}`);
  output('changed', changed);
  output('entries', canonical.entries.length);
  output('pending', pending);
  return { changed, feed: canonical };
}

/* ------------------------------------------------------------------ GitHub REST (no deps) */

function authToken() {
  const fromEnv = process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
  if (fromEnv) return fromEnv;
  try { return execFileSync('gh', ['auth', 'token'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); } catch { return ''; }
}

async function apiFetch(path, { method = 'GET', body } = {}) {
  const headers = {
    accept: 'application/vnd.github+json',
    'x-github-api-version': '2022-11-28',
    'user-agent': 'whats-new-sync',
    ...(body ? { 'content-type': 'application/json' } : {}),
  };
  const token = authToken();
  if (token) headers.authorization = `Bearer ${token}`;
  const url = path.startsWith('http') ? path : `https://api.github.com${path}`;
  const response = await fetch(url, { method, headers, ...(body ? { body: JSON.stringify(body) } : {}) });
  if (!response.ok) throw new Error(`fetch → ${response.status}: ${(await response.text()).slice(0, 300)}`);
  return response.status === 204 ? null : response.json();
}

/** `gh api` fallback for environments whose Node TLS store cannot reach api.github.com. */
function apiGh(path, { method = 'GET', body } = {}) {
  const args = ['api', path, '-X', method, '-H', 'Accept: application/vnd.github+json'];
  const input = body ? JSON.stringify(body) : undefined;
  if (input) args.push('--input', '-');
  const out = execFileSync('gh', args, {
    cwd: ROOT, encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'], maxBuffer: 32 * 1024 * 1024,
    ...(input ? { input } : {}),
  }).trim();
  return out ? JSON.parse(out) : null;
}

async function api(path, options = {}) {
  try {
    return await apiFetch(path, options);
  } catch (fetchError) {
    try {
      return apiGh(path, options);
    } catch (ghError) {
      const detail = ghError instanceof Error ? (ghError.stderr?.toString?.() || ghError.message) : String(ghError);
      throw new Error(`GitHub API ${options.method ?? 'GET'} ${path} failed — ${fetchError instanceof Error ? fetchError.message : String(fetchError)}; gh api fallback: ${String(detail).slice(0, 300)}`);
    }
  }
}

function repoSlug() {
  if (process.env.GITHUB_REPOSITORY) return process.env.GITHUB_REPOSITORY;
  const remote = execFileSync('git', ['remote', 'get-url', 'origin'], { cwd: ROOT, encoding: 'utf8' }).trim();
  const match = remote.match(/github\.com[:/]([^/]+)\/([^/]+?)(?:\.git)?$/);
  if (!match) throw new Error(`cannot determine owner/repo from origin: ${remote}`);
  return `${match[1]}/${match[2]}`;
}

function asPullRequest(raw) {
  return {
    number: raw.number,
    title: String(raw.title ?? ''),
    body: raw.body ?? '',
    createdAt: raw.created_at,
    mergedAt: raw.merged_at ?? null,
    merged: Boolean(raw.merged ?? raw.merged_at),
    state: raw.state ?? (raw.merged_at ? 'closed' : 'open'),
    htmlUrl: raw.html_url,
    labels: (raw.labels ?? []).map((l) => (typeof l === 'string' ? l : l.name)).filter(Boolean),
    author: raw.user?.login ?? '',
    authorIsBot: raw.user?.type === 'Bot',
  };
}

async function fetchPullRequest(number) {
  return asPullRequest(await api(`/repos/${repoSlug()}/pulls/${number}`));
}

/* ------------------------------------------------------------------ feed transitions */

async function applyPullRequest(feed, pr, stage, d) {
  if (!d.shouldPublishPullRequest(pr)) {
    console.log(`whats-new: PR #${pr.number} excluded (${d.WHATS_NEW_SKIP_LABEL}, bot author, or [skip whats-new])`);
    return d.removeProposedPullRequest(feed, pr.number);
  }
  const next = d.upsertPullRequestFeed(feed, pr, stage ?? (pr.merged ? 'shipped' : 'proposed'));
  console.log(`whats-new: PR #${pr.number} → ${stage ?? (pr.merged ? 'shipped' : 'proposed')}: ${next.entries.find((e) => e.id === `WN-PR-${pr.number}`)?.title}`);
  return next;
}

async function backfill(feed, d, since) {
  const watermark = since || feed.lastMergedAt;
  const repo = repoSlug();
  const closed = [];
  for (let page = 1; page <= 3; page += 1) {
    const batch = await api(`/repos/${repo}/pulls?state=closed&sort=updated&direction=desc&per_page=100&page=${page}`);
    closed.push(...batch);
    if (batch.length < 100) break;
  }
  const merged = closed
    .filter((p) => p.merged_at && p.merged_at > watermark && p.base?.ref === 'main')
    .sort((a, b) => String(a.merged_at).localeCompare(String(b.merged_at)));
  let next = feed;
  for (const raw of merged) next = await applyPullRequest(next, asPullRequest(raw), 'shipped', d);
  // Self-heal: a PR may have merged or closed while its proposed entry was written from a fork
  // or during a failed run. The push-to-main job re-checks every open proposal.
  for (const entry of next.entries.filter((e) => e.stage === 'proposed' && e.pr)) {
    try {
      const current = await fetchPullRequest(entry.pr);
      if (current.merged) next = await applyPullRequest(next, current, 'shipped', d);
      else if (current.state === 'closed') next = d.removeProposedPullRequest(next, entry.pr);
      else next = await applyPullRequest(next, current, 'proposed', d);
    } catch (error) {
      console.warn(`whats-new: could not re-check PR #${entry.pr}: ${error instanceof Error ? error.message : String(error)}`);
    }
  }
  return next;
}

/* ------------------------------------------------------------------ sticky PR comment */

async function commentDraft(pr, entry, d) {
  if (!entry) return;
  const repo = repoSlug();
  const text = [
    COMMENT_MARKER,
    `### What's New — ${entry.stage === 'shipped' ? 'published on merge' : 'automatic draft'}`,
    '',
    `This PR is **${entry.stage}** in the operator feed as \`${entry.id}\` (${entry.category}, ${entry.risk} risk). The feed is updated automatically; no manual release-note edit is needed.`,
    '',
    `- **Why:** ${entry.why}`,
    `- **What changed:** ${entry.what}`,
    `- **What you need to do:** ${entry.whatYouNeedToDo}`,
    '',
    `Edit the PR title/labels or its \`## Why\`, \`## What changed\` and \`## What you need to do\` sections to rewrite this note; the next PR update regenerates it. Add the \`${d.WHATS_NEW_SKIP_LABEL}\` label (or \`[skip whats-new]\` in the body) to exclude an internal PR.`,
  ].join('\n');
  const comments = await api(`/repos/${repo}/issues/${pr.number}/comments?per_page=100`);
  // Marker-only match: the comment may be authored by github-actions[bot] (built-in token) or by
  // the user behind an optional PAT, so an author check would create duplicates on every edit.
  const existing = comments.find((c) => String(c.body ?? '').includes(COMMENT_MARKER));
  if (existing) await api(`/repos/${repo}/issues/comments/${existing.id}`, { method: 'PATCH', body: { body: text } });
  else await api(`/repos/${repo}/issues/${pr.number}/comments`, { method: 'POST', body: { body: text } });
  console.log(`whats-new: ${existing ? 'updated' : 'posted'} draft comment on PR #${pr.number}`);
}

/* ------------------------------------------------------------------ entry point */

async function main() {
  let feed = readFeed();
  if (has('--check')) { await writeFeed(feed, { check: true }); return; }
  const d = await domain();

  if (has('--backfill') || has('--event') || ARGV.some((a) => a.startsWith('--pr='))) {
    // modes that mutate
  } else {
    throw new Error('usage: whats-new-sync.mjs --check | --event | --backfill | --pr=<n> [--stage=...] [--comment] [--since=ISO]');
  }

  let pr = null;
  let draftForComment = null;

  const prNumber = value('pr', undefined);
  if (prNumber) {
    pr = await fetchPullRequest(Number(prNumber));
    feed = await applyPullRequest(feed, pr, value('stage', undefined), d);
    draftForComment = feed.entries.find((e) => e.id === `WN-PR-${pr.number}`);
  } else if (has('--backfill')) {
    feed = await backfill(feed, d, value('since', process.env.WHATS_NEW_SINCE));
  } else {
    const eventPath = process.env.GITHUB_EVENT_PATH;
    if (!eventPath) throw new Error('--event needs GITHUB_EVENT_PATH (GitHub Actions provides it)');
    const payload = JSON.parse(readFileSync(eventPath, 'utf8'));
    const name = process.env.GITHUB_EVENT_NAME;
    if (name === 'push' || name === 'workflow_dispatch') {
      feed = await backfill(feed, d, value('since', process.env.WHATS_NEW_SINCE));
    } else if (payload.pull_request) {
      pr = asPullRequest(payload.pull_request);
      const action = payload.action;
      if (action === 'closed' && !pr.merged) {
        feed = d.removeProposedPullRequest(feed, pr.number);
        console.log(`whats-new: PR #${pr.number} closed without merging — proposed entry removed`);
      } else {
        feed = await applyPullRequest(feed, pr, action === 'closed' ? 'shipped' : 'proposed', d);
        draftForComment = feed.entries.find((e) => e.id === `WN-PR-${pr.number}`);
      }
    } else {
      throw new Error(`unsupported event: ${name}`);
    }
  }

  await writeFeed(feed);
  // A comment is a convenience for reviewers; never let a comment API failure block publication.
  if (has('--comment') && pr && draftForComment) {
    try {
      await commentDraft(pr, draftForComment, d);
    } catch (error) {
      console.warn(`whats-new: draft comment skipped: ${error instanceof Error ? error.message : String(error)}`);
    }
  }
}

main().catch((error) => {
  console.error(`whats-new: ${error instanceof Error ? error.stack : String(error)}`);
  process.exitCode = 1;
});
