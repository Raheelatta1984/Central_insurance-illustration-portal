#!/usr/bin/env node
/**
 * api-doc.mjs — generates docs/API-REFERENCE.md from the dispatcher's case table.
 * The routes exist exactly once (`src/core/routes.ts`); the reference is derived, never
 * hand-maintained. Run via `npm run docs:api` after adding or renaming an endpoint.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const source = readFileSync(join(root, 'src/core/routes.ts'), 'utf8');
const routes = [...source.matchAll(/case\s+'(GET|POST)\s+([^']+)'/g)].map((m) => ({ method: m[1], path: m[2] }));
const unique = [...new Map(routes.map((r) => [`${r.method} ${r.path}`, r])).values()]
  .sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));

const groups = new Map();
for (const r of unique) {
  const seg = r.path.split('/').filter(Boolean)[0] ?? '(root)';
  if (!groups.has(seg)) groups.set(seg, []);
  groups.get(seg).push(r);
}

const lines = [
  '# API reference',
  '',
  `Generated by \`npm run docs:api\` from \`src/core/routes.ts\` — ${unique.length} endpoints. Do not edit by hand.`,
  '',
  '## Transport rules',
  '',
  '- Base path: `/api` (e.g. `GET /api/health`). The same dispatcher serves the Node server and the offline in-browser bundle.',
  '- Bodies are JSON objects. Malformed JSON, non-object bodies, missing/invalid identifiers, amounts, enums and booleans are refused with **400** and a sentence in `{ "error": … }`.',
  '- Bodies over 5 MB are refused with **413**.',
  '- Domain refusals (a rule said no) return **409** with the reason. Unexpected failures return **500** `{ "error": "internal error", "requestId": … }`; the detail is logged server-side under that request id (`x-request-id` header on every response).',
  '- **Idempotency:** send `Idempotency-Key: <stable key per user intent>` on POSTs. A retry with the same key and body replays the first answer (`idempotent-replay: true`) instead of applying the change twice; the same key with a different body is refused 409.',
  '- **Authentication:** set `PORTAL_AUTH_TOKENS` (or `PORTAL_API_TOKEN`) on the server and send `Authorization: Bearer …`. Without tokens the server runs in labelled **demo mode** (open). `NODE_ENV=production` refuses to boot open unless `PORTAL_ALLOW_DEMO=1`. When authenticated, the audit actor (`by`) is stamped from the token, and money/approval routes require matching roles (see `src/server/auth.ts`).',
  '- **State:** in-memory demo world, rebuilt on boot; `GET /health` reports this honestly. `POST /reset` exists for demos/tests and requires demo mode or an admin principal.',
  '- Two `GET`s perform a catch-up sync of the reporting store before answering (`/reporting/store`, `/reporting/outbox`) — they are safe to retry and answered `cache-control: no-store`, but they are not side-effect-free.',
  '',
  '## Endpoints',
  '',
];
for (const [group, rs] of [...groups.entries()].sort()) {
  lines.push(`### \`/${group}\``, '');
  for (const r of rs) lines.push(`- \`${r.method} /api${r.path}\``);
  lines.push('');
}
writeFileSync(join(root, 'docs/API-REFERENCE.md'), lines.join('\n'));
console.log(`docs/API-REFERENCE.md written (${unique.length} endpoints)`);
